#!/usr/bin/env python3

"""
Pack the web UI (src/web/) into a C file in lwIP httpd's fsdata format (design D18).

Every file is gzipped (reproducibly) and stored with its HTTP headers included
(FS_FILE_FLAGS_HEADER_INCLUDED), so httpd sends it as is. The file is included by lwIP's fs.c
(HTTPD_USE_CUSTOM_FSDATA) and matches struct fsdata_file with HTTPD_PRECALCULATED_CHECKSUM off.

Usage: mkfsdata.py <web directory> <output .c>
"""

import gzip
import io
import os
import re
import sys

CONTENT_TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".svg": "image/svg+xml",
}


def gzip_bytes(data):
    """Reproducible gzip: no timestamp, no file name, level 9."""
    out = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", compresslevel=9, fileobj=out, mtime=0) as f:
        f.write(data)
    return out.getvalue()


def http_response(name, body):
    """Complete HTTP response (headers + gzipped body) for one web file."""
    ext = os.path.splitext(name)[1].lower()
    if ext not in CONTENT_TYPES:
        raise ValueError(f"no content type for {name}")
    zipped = gzip_bytes(body)
    headers = (
        "HTTP/1.1 200 OK\r\n"
        f"Content-Type: {CONTENT_TYPES[ext]}\r\n"
        "Content-Encoding: gzip\r\n"
        f"Content-Length: {len(zipped)}\r\n"
        "Cache-Control: no-store\r\n"
        "Connection: close\r\n"
        "\r\n"
    )
    return headers.encode("ascii") + zipped


def web_files(directory):
    """(name, content) of every file in the directory, sorted by name. Hidden files (.DS_Store)
    and editor backups (name~) aren't part of the UI."""
    names = sorted(n for n in os.listdir(directory)
                   if os.path.isfile(os.path.join(directory, n)) and not n.startswith(".") and not n.endswith("~"))
    result = []
    for name in names:
        with open(os.path.join(directory, name), "rb") as f:
            result.append((name, f.read()))
    return result


def c_bytes(data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    return "\n".join(lines)


def generate(files):
    """The C source for a list of (name, content)."""
    out = [
        "// Generated by tools/mkfsdata.py from src/web/. Do not edit.",
        "",
        '#include "lwip/apps/fs.h"',
        "",
    ]
    idents = [re.sub(r"\W", "_", name) for name, _ in files]
    for (name, body), ident in zip(files, idents):
        out += [
            f"static const unsigned char data_{ident}[] = {{",
            c_bytes(http_response(name, body)),
            "};",
            "",
        ]
    # Files are chained back to front, so each one can point at the next (defined earlier)
    for n in reversed(range(len(files))):
        nxt = f"&file_{idents[n + 1]}" if n + 1 < len(files) else "NULL"
        out += [
            f"static const struct fsdata_file file_{idents[n]} = {{",
            f"    {nxt},",
            f'    (const unsigned char *)"/{files[n][0]}",',
            f"    data_{idents[n]},",
            f"    (int)sizeof(data_{idents[n]}),",
            "    FS_FILE_FLAGS_HEADER_INCLUDED,",
            "};",
            "",
        ]
    root = f"&file_{idents[0]}" if files else "((const struct fsdata_file *)NULL)"
    out += [f"#define FS_ROOT ({root})" if files else f"#define FS_ROOT {root}",
            f"#define FS_NUMFILES {len(files)}", ""]
    return "\n".join(out)


def main(argv):
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    text = generate(web_files(argv[1]))
    with open(argv[2], "w", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
